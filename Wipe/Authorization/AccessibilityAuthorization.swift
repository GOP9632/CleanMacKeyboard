import Foundation

/// 輔助使用授權那一頭。
///
/// 攔截鍵盤需要 macOS 的「輔助使用」授權。沒有它，事件攔截根本建立不起來，
/// 所以 Wipe 在拿到它之前不顯示任何可以按的開始按鈕：一顆按了沒用的按鈕
/// 對非工程背景的使用者來說就是「這個 app 壞了」（見 #9）。
///
/// 這個形狀刻意把「問狀態」與「帶使用者去打勾」放在一起。它們是同一件事的
/// 兩面，而且測試那一頭要騙的也是同一個東西：真實世界裡授權只能由使用者
/// 親手在系統設定裡給，程式沒有辦法自己打勾，也沒有辦法自己收回
/// （見 `docs/seams.md`）。
///
/// 它是查詢而不是推播，跟安全輸入探測同一個理由：系統沒有提供授權變化的
/// 通知。誰去定期問，以及問到之後怎麼辦，是 `AuthorizationGate` 的事。
@MainActor
protocol AccessibilityAuthorization: AnyObject {
    /// 現在有沒有輔助使用授權。
    var isTrusted: Bool { get }

    /// 帶使用者去系統設定的「輔助使用」那一頁。
    ///
    /// 引導畫面上那顆按鈕按下去做的就是這件事。使用者不必自己在深層選單裡找。
    func openSettings()
}
