import Foundation

/// 清潔流程控制器的安全輸入探測。
///
/// 安全輸入模式是 macOS 在密碼欄位取得焦點時啟動的保護機制，啟動期間所有
/// 第三方鍵盤攔截都會被系統繞過。對 Wipe 而言這是最危險的失效來源：清潔模式
/// 看起來正常運作，鍵盤其實還活著。
///
/// 這是控制器的注入相依之一，所以「偵測到就拒絕進入」與「進行中偵測到就
/// 立刻退出」兩條規則都測得到，不需要真的把某個密碼欄位叫出來
/// （見 `docs/seams.md`）。
///
/// 它刻意是**查詢**而不是推播，跟鍵盤與機器那兩個來源不同：安全輸入模式是一個
/// 持續的狀態，不是一個瞬間的事件，而且系統沒有提供變化通知。控制器在清潔中
/// 本來就每一格都在跑，順手問一次就好。
@MainActor
protocol SecureInputProbe: AnyObject {
    /// 現在是不是處於安全輸入模式。
    ///
    /// 這個值在清潔模式期間每一格都會被讀一次，所以它必須便宜。
    var isSecureInputActive: Bool { get }

    /// 造成安全輸入模式的 app 名稱。查不出來時是 `nil`。
    ///
    /// 只在真的要拒絕的時候才會被讀，所以它可以貴一點。查不出來不代表沒事：
    /// 拒絕照樣成立，只是畫面上少了一句「去關掉哪個 app」。
    var responsibleAppName: String? { get }
}
