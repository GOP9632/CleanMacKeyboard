import Foundation

/// 拒絕進入清潔模式的理由。
///
/// 這是控制器對外可觀察的值之一（見 `docs/seams.md`）。它存在的理由是誠實：
/// 使用者正是因為相信畫面上的狀態才敢閉著眼睛擦，所以「沒進去」與「為什麼
/// 沒進去」都必須說出口，不能只是安靜地什麼都不做。
///
/// 它放在 Flow 底下而不是跟安全輸入探測擺在一起，因為它是流程的詞彙不是
/// 探測的詞彙：日後多一個跟安全輸入無關的拒絕理由（例如授權還沒給），
/// 那個 case 也長在這裡。
enum CleaningRefusal: Equatable {
    /// 安全輸入模式啟動中。
    /// - Parameter appName: 造成它的 app，查不出來時是 `nil`。
    case secureInput(appName: String?)

    /// 輸入攔截建立不起來。
    ///
    /// 走到這裡代表系統說有輔助使用授權（不然主視窗顯示的是授權引導畫面，
    /// 根本按不到開始），但攔截器就是裝不上去。最常見的原因是授權清單記著的
    /// 是舊的簽章身分，而那件事只有重開 Wipe 解得掉，所以畫面上這一句話
    /// 要直接叫使用者重開。
    case interceptionUnavailable
}
